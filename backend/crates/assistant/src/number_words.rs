//! Number words that `prompt/words.tsv` does not list (robustness finding attack_03, lead decision:
//! `words.tsv` stays word for word as D6-system-prompt Section 6 has it; this file adds
//! its own list, and `check.rs` refuses a word of the file OR of this list. Adding the words to
//! `words.tsv` later is a decision for Umar).
//!
//! `words.tsv` has the Urdu numbers 1 to 25 and the tens, so a figure could be typed in words as
//! "اٹھائیس" (28) or "ننانوے" (99). Here is every Urdu number word 1 to 99 with its common spelling
//! variants, the Urdu names of the big steps, and the Roman Urdu number words. FR-7.76 and NFR-AI-1:
//! the model writes no figure, in digits or in words.
//!
//! Words that are also everyday words are left out, so a normal answer is not refused:
//! - Urdu: `اسی` (80) is also "this very" (اسی رفتار سے) and `بہتر` (72) is "better". They are
//!   refused only before a unit word (`اسی روپے`, `بہتر فیصد`), see [`UNIT_PHRASES`]. A bare `اسی`
//!   or `بہتر` is not a number word here.
//! - Roman Urdu: `do` (2), `teen` (3) and `char` (4) are English words too. They are left out, as
//!   an English answer would never use them as Roman Urdu numbers. `kharab` is left out too: it
//!   is the usual word for spoiled goods.
//!
//! Not covered: ordinals (`بیسویں`), which can carry a figure; only the number words are.
//!
//! The matching is by whole words after the text is normalised (`ي` to `ی`), like `words.tsv`.
//!
//! Example: `اٹھائیس بل` has a number word (28); `اسی رفتار سے` has none.

